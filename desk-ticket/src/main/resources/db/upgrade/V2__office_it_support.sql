    UNIQUE KEY `uk_it_service_event__action` (`actor_id`, `client_action_id`),
    KEY `idx_it_service_event__service` (`service_item_id`, `created_at`, `id`),
    KEY `idx_it_service_event__entitlement` (`entitlement_id`, `created_at`, `id`),
    CONSTRAINT `ck_it_service_event__id_contract` CHECK (REGEXP_LIKE(`id`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_event__service_item_id_contract` CHECK (REGEXP_LIKE(`service_item_id`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_event__entitlement_id_contract` CHECK (`entitlement_id` IS NULL OR (REGEXP_LIKE(`entitlement_id`, '^[0-9a-f]{32}$', 'c'))),
    CONSTRAINT `ck_it_service_event__actor_id_contract` CHECK (REGEXP_LIKE(`actor_id`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_event__event_type_contract` CHECK (REGEXP_LIKE(`event_type`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_event__client_action_id_contract` CHECK (REGEXP_LIKE(`client_action_id`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_event__request_hash_contract` CHECK (REGEXP_LIKE(`request_hash`, '^[0-9a-f]{64}$', 'c')),
    CONSTRAINT `ck_it_service_event__details_contract` CHECK (JSON_SCHEMA_VALID('{"type":"object","required":["schema_version"],"properties":{"schema_version":{"type":"integer","minimum":1}}}', `details`) = 1),
    CONSTRAINT `ck_it_service_event__event_type_values` CHECK (`event_type` IN ('SERVICE_CREATED', 'SERVICE_UPDATED', 'SERVICE_DISABLED', 'ENTITLEMENT_GRANTED', 'ENTITLEMENT_UPDATED', 'ENTITLEMENT_SUSPENDED', 'ENTITLEMENT_RESUMED')),
    CONSTRAINT `ck_it_service_event__business_1` CHECK ((((event_type LIKE 'SERVICE_%' AND entitlement_id IS NULL) OR (event_type LIKE 'ENTITLEMENT_%' AND entitlement_id IS NOT NULL)) IS TRUE))) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin ROW_FORMAT=DYNAMIC COMMENT='服务目录与资格变更事件';

