    `event_type` VARCHAR(32) NOT NULL COMMENT 'SERVICE_CREATED / SERVICE_UPDATED / SERVICE_DISABLED / ENTITLEMENT_GRANTED / ENTITLEMENT_UPDATED / ENTITLEMENT_SUSPENDED / ENTITLEMENT_RESUMED',
