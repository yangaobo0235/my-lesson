CREATE TABLE `it_service_item` (
    `id` VARCHAR(32) NOT NULL COMMENT '主键',
    `service_code` VARCHAR(64) NOT NULL COMMENT '规范化大写ASCII稳定代码，全局唯一且停用不复用',
    `category` VARCHAR(32) NOT NULL COMMENT 'TERMINAL / PRINTING / NETWORK / OFFICE_SOFTWARE',
    `service_name` VARCHAR(100) NOT NULL COMMENT '客户可理解的项目名称',
    `support_scope` TEXT NOT NULL COMMENT '明确支持产品、环境、版本及排除条件，最多5000字符',
    `onsite_supported` BOOLEAN NOT NULL DEFAULT FALSE COMMENT '项目是否允许人工开放现场服务',
    `status` VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE / DISABLED',
    `created_by` VARCHAR(32) NOT NULL COMMENT '外部系统管理员账号',
    `updated_by` VARCHAR(32) NOT NULL COMMENT '最后维护管理员账号',
