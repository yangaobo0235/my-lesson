    `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '记录创建时间',
    `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '显式维护更新时间',
    `row_version` BIGINT NOT NULL DEFAULT 0 COMMENT '非负，比较后递增',
    CONSTRAINT `pk_it_service_item` PRIMARY KEY (`id`),
    UNIQUE KEY `uk_it_service_item__code` (`service_code`),
    KEY `idx_it_service_item__category` (`category`, `status`, `id`),
    CONSTRAINT `ck_it_service_item__id_contract` CHECK (REGEXP_LIKE(`id`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_item__service_code_contract` CHECK (REGEXP_LIKE(`service_code`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__category_contract` CHECK (REGEXP_LIKE(`category`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__service_name_contract` CHECK (REGEXP_LIKE(`service_name`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__support_scope_contract` CHECK (REGEXP_LIKE(`support_scope`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__onsite_supported_contract` CHECK (`onsite_supported` IN (0, 1)),
    CONSTRAINT `ck_it_service_item__status_contract` CHECK (REGEXP_LIKE(`status`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__created_by_contract` CHECK (REGEXP_LIKE(`created_by`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_item__updated_by_contract` CHECK (REGEXP_LIKE(`updated_by`, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT `ck_it_service_item__change_reason_contract` CHECK (REGEXP_LIKE(`change_reason`, '[^[:space:]]')),
    CONSTRAINT `ck_it_service_item__row_version_contract` CHECK (`row_version` >= 0),
    CONSTRAINT `ck_it_service_item__category_values` CHECK (`category` IN ('TERMINAL', 'PRINTING', 'NETWORK', 'OFFICE_SOFTWARE')),
    CONSTRAINT `ck_it_service_item__status_values` CHECK (`status` IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT `ck_it_service_item__update_time_contract` CHECK (updated_at >= created_at),
    CONSTRAINT `ck_it_service_item__business_1` CHECK (((REGEXP_LIKE(service_code, '^[A-Z][A-Z0-9_]{0,63}$', 'c')) IS TRUE)),
    CONSTRAINT `ck_it_service_item__business_2` CHECK (((CHAR_LENGTH(support_scope) <= 5000) IS TRUE))) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin ROW_FORMAT=DYNAMIC COMMENT='支持服务项目';

