@dataclass(frozen=True)
class Case:
    """隐藏环境仅交给模拟器和评分器，case ID不作为模型上下文。"""

    family: Family
    branch: int

    @property
    def identifier(self) -> str:
        """稳定实例身份用于冻结清单及三次独立重复。"""
        return f"{self.family.key}-{self.branch + 1}"

    @property
    def expected(self) -> str:
        """预先标签不随模型输出调整，不能全部交接刷解决率。"""
        return "RESOLVED" if self.branch == 0 else "HANDOVER"


CASES = tuple(Case(family, branch) for family in FAMILIES for branch in range(3))
